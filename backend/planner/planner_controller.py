# ── Response Schema ───────────────────────────────────────────────────────────

class ScheduledTask(BaseModel):
    start_time: str
    end_time: str
    task_name: str
    task_type: str
    priority: str
    reason: str

class PlanSummary(BaseModel):
    academic_focus: int
    placement_focus: int
    reason: str

class PlannerResponse(BaseModel):
    plan_summary: PlanSummary
    schedule: List[ScheduledTask]
    productivity_advice: List[str]
    adaptive_insights: List[str] = []


# ── Pipeline ──────────────────────────────────────────────────────────────────

def run_planning_pipeline(user_data: dict, target_date: str) -> dict:
    """
    Runs the full 5-stage planning pipeline.
    Returns a complete, validated plan dict.
    """
    # Stage 1: Analyze priorities
    logger.info("[Pipeline] Stage 1: Priority Analysis...")
    analysis = analyze(user_data)
    logger.info(f"[Pipeline]  Academic={analysis['academic_weight']}% | Placement={analysis['placement_weight']}% | Hours={analysis['adjusted_hours']}")

    # Stage 2: Select tasks (WHAT)
    logger.info("[Pipeline] Stage 2: Task Selection...")
    tasks = select_tasks(user_data, analysis)
    logger.info(f"[Pipeline]  Selected {len(tasks)} tasks: {[t['name'] for t in tasks]}")

    # Stage 3: Schedule tasks (WHEN)
    logger.info("[Pipeline] Stage 3: Timetable Generation...")
    timetable = build_timetable(tasks, user_data, analysis)
    logger.info(f"[Pipeline]  Generated {len(timetable)} time slots.")

    # Extract adaptive insights generated by progress analytics
    adaptive_insights = user_data.get("_progress_analytics", {}).get("planner_adaptation", {}).get("adaptations", [])
    
    # Stage 4: Build base plan (used as fallback if AI fails)
    base_plan = {
        "plan_summary": {
            "academic_focus": analysis["academic_weight"],
            "placement_focus": analysis["placement_weight"],
            "reason": analysis["reason"]
        },
        "schedule": timetable,
        "productivity_advice": _generate_fallback_advice(user_data, analysis),
        "adaptive_insights": adaptive_insights
    }

    # Stage 5: Gemini Enhancement
    logger.info("[Pipeline] Stage 5: Gemini Enhancement...")
    try:
        prompt = build_enhancement_prompt(user_data, analysis, timetable, target_date)
        enhanced = enhance_schedule(prompt)

        if enhanced and _validate(enhanced):
            # Ensure AI didn't accidentally change time slots
            enhanced = _protect_timeslots(enhanced, timetable)
            enhanced["adaptive_insights"] = adaptive_insights
            logger.info("[Pipeline] ✅ AI enhancement accepted.")
            return enhanced
        else:
            logger.warning("[Pipeline] ⚠️  AI enhancement rejected — using deterministic plan.")
    except Exception as e:
        logger.error(f"[Pipeline] AI enhancement failed: {e}")

    return base_plan


def _validate(plan: dict) -> bool:
    """Strict validation of the AI-returned plan."""
    if not isinstance(plan, dict):
        return False
    if "plan_summary" not in plan or "schedule" not in plan:
        return False
    if not isinstance(plan["schedule"], list) or len(plan["schedule"]) == 0:
        return False
    required_keys = {"start_time", "end_time", "task_name", "task_type", "priority", "reason"}
    for task in plan["schedule"]:
        if not required_keys.issubset(task.keys()):
            logger.error(f"[Validate] Task missing keys: {required_keys - set(task.keys())}")
            return False
    return True


def _protect_timeslots(enhanced: dict, original_timetable: list) -> dict:
    """
    Ensures the AI did not hallucinate different time slots.
    Overwrites AI-returned start/end times with the deterministic ones.
    """
    original_slots = [(t["start_time"], t["end_time"]) for t in original_timetable]
    for i, task in enumerate(enhanced.get("schedule", [])):
        if i < len(original_slots):
            task["start_time"] = original_slots[i][0]
            task["end_time"] = original_slots[i][1]
    return enhanced


def _generate_fallback_advice(user_data: dict, analysis: dict) -> List[str]:
    """Generates personalized productivity advice without AI."""
    advice = []
    distraction = user_data.get("biggest_distraction", "social media")
    burnout = analysis.get("burnout", "low")
    stress = user_data.get("stress_level", "medium")
    consistency = analysis.get("consistency", "medium")
    focus = user_data.get("focus_capacity", "60 mins")

    advice.append(f"Since '{distraction}' is your biggest distraction, try app blockers or keeping your phone in another room during study blocks.")

    if burnout == "high":
        advice.append("Your burnout is high — honor every break. Skipping breaks today will cost you more tomorrow.")
    elif burnout == "medium":
        advice.append("Take every scheduled break seriously. Even 15 minutes of rest resets your focus.")

    if stress == "high":
        advice.append("High stress can impair memory. Try 5 minutes of deep breathing before starting any difficult task.")

    if consistency == "low":
        advice.append("Focus on finishing just ONE task fully before moving to the next. Small wins build momentum.")

    if "30" in focus or "45" in focus:
        advice.append(f"Your focus capacity is {focus}. Use strict Pomodoro sessions — work hard for that time, then rest completely.")
    else:
        advice.append("Aim for uninterrupted 60-minute deep work blocks. Close all notifications before starting.")

    return advice


# ── FastAPI Route ─────────────────────────────────────────────────────────────

@router.post("/generate", response_model=PlannerResponse)
def api_generate_plan(request: PlannerRequest, user_id: str = "temp-user", db: Session = Depends(get_db)):
    """
    POST /api/planner/generate
    Runs the full 5-stage planning pipeline and returns a complete daily plan.
    """
    user_data = request.model_dump()
    target_date = user_data.pop("date")

    # ----- ADAPTIVE PROGRESS INJECTION -----
    records = db.query(Progress).filter(Progress.user_id == user_id).order_by(Progress.date).all()
    schedule_records = db.query(Schedule).filter(Schedule.user_id == user_id).order_by(Schedule.date).all()
    
    if records or schedule_records:
        rec_dicts = [{"date": r.date, "study_hours": r.study_hours, "completed_tasks": r.completed_tasks, "missed_tasks": r.missed_tasks, "productivity_score": r.productivity_score} for r in records]
        sched_dicts = [{"date": s.date, "task_name": s.task_name, "task_type": s.task_type, "status": s.status, "start_time": getattr(s, "notes", "09:00 AM")} for s in schedule_records]
        
        analytics = build_full_analytics(rec_dicts, sched_dicts)
        
        # Override user inputs with AI-detected reality
        adapt = analytics.get("planner_adaptation", {}).get("adjustments", {})
        if "suggested_hours" in adapt:
            user_data["available_study_hours"] = adapt["suggested_hours"]
        if analytics.get("burnout", {}).get("risk") in ["medium", "high"]:
            user_data["burnout_level"] = analytics["burnout"]["risk"]
        
        user_data["_progress_analytics"] = analytics # Pass full analytics down the pipeline

    logger.info(f"[API] Plan requested for {target_date} | Burnout={user_data.get('burnout_level')} | Exams={user_data.get('upcoming_exams')}")

    plan = run_planning_pipeline(user_data, target_date)

    if not plan or not plan.get("schedule"):
        raise HTTPException(status_code=500, detail="Planning pipeline failed to generate a schedule.")

    # Save the generated plan to the Schedule database so we can track skips/completions tomorrow!
    try:
        # Clear existing schedule for this date to prevent duplicates
        db.query(Schedule).filter(Schedule.user_id == user_id, Schedule.date == target_date).delete()
        
        for t in plan["schedule"]:
            dur_str = t.get("end_time", "10:00 AM") # basic approximation, scheduler logic is complex
            db.add(Schedule(
                user_id=user_id,
                date=target_date,
                task_name=t["task_name"],
                task_type=t["task_type"],
                priority=t["priority"],
                status="pending",
                notes=t["start_time"] # Store start time in notes to analyze morning vs evening skips
            ))
        db.commit()
    except Exception as e:
        logger.error(f"[API] Failed to save schedule to DB: {e}")
        db.rollback()

    return plan
